-- PostgreSQL schema for payment-processor, used by the clustered (k8s) profile.
--
-- Mirrors the H2 src/main/resources/schema.sql but drops the H2-only dialect
-- bits: CLOB becomes TEXT, AUTO_INCREMENT becomes an identity column and the
-- in-place ALTER migrations are unnecessary for a freshly created database.
CREATE TABLE IF NOT EXISTS processed_payment (
    payment_id   VARCHAR(64) PRIMARY KEY,
    account_id   VARCHAR(64),
    amount       DECIMAL(19, 2),
    currency     VARCHAR(8),
    status       VARCHAR(16) NOT NULL, -- IN_PROGRESS | COMPLETED | FAILED
    reason       VARCHAR(255),
    claimed_at   TIMESTAMP NOT NULL,
    completed_at TIMESTAMP
);

CREATE TABLE IF NOT EXISTS gateway_charge (
    payment_id VARCHAR(64) PRIMARY KEY,
    successful BOOLEAN     NOT NULL,
    reason     VARCHAR(255),
    charged_at TIMESTAMP   NOT NULL
);

CREATE TABLE IF NOT EXISTS outbox (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_id      VARCHAR(64)  NOT NULL,
    topic           VARCHAR(64)  NOT NULL,
    message_key     VARCHAR(64),
    payload         TEXT         NOT NULL,
    status          VARCHAR(16)  NOT NULL DEFAULT 'PENDING', -- PENDING | PUBLISHED | FAILED
    attempts        INT          NOT NULL DEFAULT 0,
    last_error      VARCHAR(512),
    next_attempt_at TIMESTAMP,
    created_at      TIMESTAMP    NOT NULL,
    published_at    TIMESTAMP,
    CONSTRAINT ux_outbox_payment_topic UNIQUE (payment_id, topic)
);

-- Backs the relay's lease-based claiming query (status + next_attempt_at + id).
CREATE INDEX IF NOT EXISTS ix_outbox_claimable
    ON outbox (status, next_attempt_at, id);
